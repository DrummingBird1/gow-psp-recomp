"""Compiles runtime/shaders/*.hlsl for every SDL3 GPU backend into runtime/gpu_shaders.h.

SPIR-V (Vulkan) comes from the Vulkan SDK's dxc (it has SPIR-V code generation); DXIL
(Direct3D 12) from the Windows SDK's dxc, whose dxil.dll signs the output. The generated
header is committed, so building the runtime does not need either SDK; only changing the
shaders does.

Usage: .venv/Scripts/python -I tools/build_shaders.py [--vulkan-dxc PATH] [--windows-dxc PATH]
"""
import argparse
import glob
import os
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHADERS = [  # (source, entry point, profile, name in the header)
    ("ge.hlsl", "vs_main", "vs_6_0", "ge_vs"),
    ("ge.hlsl", "fs_main", "ps_6_0", "ge_fs"),
]


def find_vulkan_dxc() -> str:
    sdk = os.environ.get("VULKAN_SDK")
    if sdk and Path(sdk, "Bin", "dxc.exe").exists():
        return str(Path(sdk, "Bin", "dxc.exe"))
    sys.exit("Vulkan SDK dxc not found: set VULKAN_SDK or pass --vulkan-dxc")


def find_windows_dxc() -> str:
    hits = sorted(glob.glob(r"C:\Program Files (x86)\Windows Kits\10\bin\10.*\x64\dxc.exe"))
    if hits:
        return hits[-1]
    sys.exit("Windows SDK dxc not found: pass --windows-dxc")


def compile_one(dxc: str, src: Path, entry: str, profile: str, spirv: bool) -> bytes:
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp, "out.bin")
        cmd = [dxc, "-nologo", "-T", profile, "-E", entry, "-O3", "-Fo", str(out), str(src)]
        if spirv:
            cmd[1:1] = ["-spirv", "-fspv-target-env=vulkan1.0"]
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode != 0:
            sys.exit(f"{' '.join(cmd)}\n{r.stdout}{r.stderr}")
        return out.read_bytes()


def c_array(name: str, data: bytes) -> str:
    rows = [", ".join(f"0x{b:02X}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return f"static const unsigned char {name}[{len(data)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--vulkan-dxc")
    ap.add_argument("--windows-dxc")
    a = ap.parse_args()
    vk, win = a.vulkan_dxc or find_vulkan_dxc(), a.windows_dxc or find_windows_dxc()
    parts = ["/* Generated by tools/build_shaders.py from runtime/shaders/*.hlsl - do not edit. */\n#pragma once\n\n"]
    for src, entry, profile, name in SHADERS:
        path = ROOT / "runtime" / "shaders" / src
        spv = compile_one(vk, path, entry, profile, True)
        dxil = compile_one(win, path, entry, profile, False)
        parts.append(c_array(f"{name}_spirv", spv))
        parts.append(c_array(f"{name}_dxil", dxil))
        print(f"{name}: SPIR-V {len(spv)} bytes, DXIL {len(dxil)} bytes")
    (ROOT / "runtime" / "gpu_shaders.h").write_text("\n".join(parts), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
